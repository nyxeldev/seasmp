export type Locale = keyof typeof T
export type TKey = keyof typeof T['uz']

interface LocaleStore {
  locale: Locale
  setLocale: (l: Locale) => void
  t: (key: TKey) => string
}

export const useLocale = create<LocaleStore>()(
  persist(
    (set, get) => ({
      locale: 'uz',
      setLocale: (locale) => set({ locale }),
      t: (key) => (T[get().locale] as Record<string, string>)[key] ?? key,
    }),
    { name: 'seasmp-locale' }
  )
)

// backward-compat alias
export const useLocaleStore = useLocale
